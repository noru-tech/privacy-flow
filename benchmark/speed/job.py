#!/usr/bin/env python3
"""Time piiflow and Privado on one corpus application, on this machine (the speed benchmark).

    python3 benchmark/speed/job.py <app> --piiflow <binary> --rules <privado rules> --out <dir>

Run by .github/workflows/benchmark-speed.yml on a GitHub-hosted runner, after fetch.py has
fetched the application. piiflow runs `--repeat` times (default 3) under /usr/bin/time; its
document must equal the recorded benchmark run's byte for byte, which also checks that a Linux
build gives the same results as the macOS one. Privado runs once, with the protocol's command
(PROTOCOL.md §8), and its memory is read from Docker once a second. Writes <out>/<app>.json.
"""
import argparse
import hashlib
import json
import os
import pathlib
import platform
import re
import subprocess
import sys
import time

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE.parent / "privado"))
import scan  # noqa: E402  (Privado's pinned image and command)


def machine():
    info = {"system": platform.system(), "machine": platform.machine(), "cpus": os.cpu_count()}
    try:
        mem = re.search(r"MemTotal:\s+(\d+) kB", pathlib.Path("/proc/meminfo").read_text())
        info["memory_gib"] = round(int(mem.group(1)) / 1024 / 1024, 1)
        model = re.search(r"model name\s*:\s*(.+)", pathlib.Path("/proc/cpuinfo").read_text())
        info["cpu"] = model.group(1).strip() if model else None
    except OSError:
        pass
    info["runner"] = os.environ.get("ImageOS", "") + " " + os.environ.get("ImageVersion", "")
    return info


def run_piiflow(binary, entry, repeat):
    """Same invocation as run.py, so the document can be compared with the recorded run."""
    name = entry["name"]
    cfg = ROOT / ".benchmark-cache/results" / name / "config.yml"
    cfg.parent.mkdir(parents=True, exist_ok=True)
    cfg.write_text("# Generated by benchmark/run.py from corpus.json: exclusions only.\nversion: 1\n"
                   + ("exclude:\n" + "".join(f"  - {json.dumps(g)}\n" for g in entry["exclude"]) if entry["exclude"] else ""))
    rel = lambda p: os.path.relpath(p, ROOT)
    doc = ROOT / ".benchmark-cache/results" / name / "flows.json"
    runs = []
    for _ in range(repeat):
        cmd = ["/usr/bin/time", "-v", binary, "-q", "scan", rel(ROOT / ".benchmark-cache" / name / entry["scope"]),
               "--config", rel(cfg), "-o", rel(doc)]
        start = time.perf_counter()
        proc = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
        wall = time.perf_counter() - start
        rss = re.search(r"Maximum resident set size \(kbytes\): (\d+)", proc.stderr)
        runs.append({"exit_code": proc.returncode, "wall_seconds": round(wall, 3),
                     "peak_rss_mib": round(int(rss.group(1)) / 1024) if rss else None})
    digest = hashlib.sha256(doc.read_bytes()).hexdigest()
    recorded = {a["name"]: a for a in json.loads((ROOT / "benchmark/results/summary.json").read_text())["applications"]}
    return {"runs": runs, "document_sha256": digest,
            "identical_to_recorded_run": digest == recorded[name]["document_sha256"],
            "version": subprocess.run([binary, "--version"], capture_output=True, text=True).stdout.strip()}


def run_privado(entry, rules, out):
    work = out / f".work-{entry['name']}"
    scan.prepare_work(entry, ROOT / ".benchmark-cache" / entry["name"] / entry["scope"], work)
    name = "pf-speed-" + entry["name"]
    subprocess.run(["docker", "rm", "-f", name], capture_output=True)
    cmd = scan.command(work, rules, entry["language"], 14, 0, 12, run_args=("-d", "--name", name))
    start = time.perf_counter()
    subprocess.run(cmd, check=True, capture_output=True, text=True)
    peak = 0.0
    while True:
        state = subprocess.run(["docker", "inspect", "-f", "{{.State.Running}}", name], capture_output=True, text=True).stdout.strip()
        if state != "true":
            break
        usage = subprocess.run(["docker", "stats", "--no-stream", "--format", "{{.MemUsage}}", name],
                               capture_output=True, text=True).stdout.split("/")[0].strip()
        m = re.match(r"([\d.]+)\s*([KMG]i?B)", usage)
        if m:
            scale = {"KiB": 1 / 1024, "MiB": 1, "GiB": 1024, "KB": 1 / 1024, "MB": 1, "GB": 1024}[m.group(2)]
            peak = max(peak, float(m.group(1)) * scale)
        time.sleep(1)
    wall = time.perf_counter() - start
    exit_code = int(subprocess.run(["docker", "inspect", "-f", "{{.State.ExitCode}}", name], capture_output=True, text=True).stdout.strip() or -1)
    oom = subprocess.run(["docker", "inspect", "-f", "{{.State.OOMKilled}}", name], capture_output=True, text=True).stdout.strip() == "true"
    subprocess.run(["docker", "rm", "-f", name], capture_output=True)
    finished = (work / ".privado" / "privado.json").exists()
    return {"exit_code": exit_code, "wall_seconds": round(wall, 1), "peak_memory_mib": round(peak),
            "finished": finished, "out_of_memory": oom or exit_code == 137, "image": scan.IMAGE,
            "memory_limit_gib": 14}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("app")
    ap.add_argument("--piiflow", required=True)
    ap.add_argument("--rules", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--repeat", type=int, default=3)
    args = ap.parse_args()
    corpus = json.loads((ROOT / "benchmark/corpus.json").read_text())
    entry = next(e for e in corpus["repositories"] if e["name"] == args.app)
    out = pathlib.Path(args.out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    result = {"app": entry["name"], "machine": machine(), "piiflow": run_piiflow(os.path.abspath(args.piiflow), entry, args.repeat)}
    result["privado"] = run_privado(entry, args.rules, out)
    (out / f"{entry['name']}.json").write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
    print(json.dumps(result, sort_keys=True))


if __name__ == "__main__":
    main()
