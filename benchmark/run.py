#!/usr/bin/env python3
"""Run piiflow on every corpus application and record what it reports (PROTOCOL.md §7, step 1).

    cargo build --release
    python3 benchmark/run.py [--binary target/release/piiflow] [--cache .benchmark-cache] [name ...]

Writes each application's flow-facts document to <cache>/results/<name>/flows.json (not
committed: it contains excerpts of the application's code) and a summary to
benchmark/results/summary.json (committed): the piiflow commit under test, the binary's digest,
and per application the document digest, exit code, counts, wall time and peak memory. Running
it twice produces the same digests; that is checked when --repeat is given.
"""
import argparse
import hashlib
import json
import pathlib
import platform
import re
import subprocess
import sys
import time

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent


def sha256(path):
    return hashlib.sha256(pathlib.Path(path).read_bytes()).hexdigest()


def peak_rss_cmd(cmd):
    """Run cmd under /usr/bin/time; return (exit code, wall seconds, peak RSS in MiB)."""
    if platform.system() == "Darwin":
        timed = ["/usr/bin/time", "-l", *cmd]
        pattern, scale = r"(\d+)\s+maximum resident set size", 1 / (1024 * 1024)
    else:
        timed = ["/usr/bin/time", "-v", *cmd]
        pattern, scale = r"Maximum resident set size \(kbytes\): (\d+)", 1 / 1024
    start = time.perf_counter()
    proc = subprocess.run(timed, capture_output=True, text=True)
    wall = time.perf_counter() - start
    m = re.search(pattern, proc.stderr)
    rss = round(int(m.group(1)) * scale) if m else None
    return proc.returncode, wall, rss, proc.stderr


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--binary", default=str(ROOT / "target/release/piiflow"))
    ap.add_argument("--cache", default=str(ROOT / ".benchmark-cache"))
    ap.add_argument("--repeat", action="store_true", help="run twice and require identical digests")
    ap.add_argument("names", nargs="*")
    args = ap.parse_args()

    corpus = json.loads((HERE / "corpus.json").read_text())
    cache = pathlib.Path(args.cache)
    version = subprocess.run([args.binary, "--version"], capture_output=True, text=True, check=True).stdout.strip()
    commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()
    dirty = bool(subprocess.run(["git", "status", "--porcelain", "--", "src", "catalogue", "Cargo.lock"], cwd=ROOT, capture_output=True, text=True).stdout.strip())

    summary_path = HERE / "results" / "summary.json"
    previous = json.loads(summary_path.read_text()) if summary_path.exists() else {}
    apps = {a["name"]: a for a in previous.get("applications", [])}
    for entry in corpus["repositories"]:
        name = entry["name"]
        if args.names and name not in args.names:
            continue
        repo = cache / name
        head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=repo, capture_output=True, text=True).stdout.strip()
        if head != entry["commit"]:
            sys.exit(f"{name}: {repo} is at {head or 'nothing'}, corpus.json pins {entry['commit']}; run fetch.py")
        out = cache / "results" / name
        out.mkdir(parents=True, exist_ok=True)
        config = out / "config.yml"
        config.write_text("# Generated by benchmark/run.py from corpus.json: exclusions only.\nversion: 1\n"
                          + ("exclude:\n" + "".join(f"  - {json.dumps(g)}\n" for g in entry["exclude"]) if entry["exclude"] else ""))
        doc = out / "flows.json"
        cmd = [args.binary, "-q", "scan", str(repo / entry["scope"]), "--config", str(config), "-o", str(doc)]
        code, wall, rss, err = peak_rss_cmd(cmd)
        if code not in (0, 1, 4):
            sys.exit(f"{name}: piiflow exited {code}\n{err}")
        digest = sha256(doc)
        if args.repeat:
            again = out / "flows.again.json"
            subprocess.run([*cmd[:-1], str(again)], check=False, capture_output=True)
            if sha256(again) != digest:
                sys.exit(f"{name}: two runs produced different documents")
            again.unlink()
        d = json.loads(doc.read_text())
        s = d["summary"]
        apps[name] = {
            "name": name,
            "repository": entry["repository"],
            "commit": entry["commit"],
            "scope": entry["scope"],
            "exit_code": code,
            "document_sha256": digest,
            "files": d["subject"]["files"],
            "languages": d["subject"]["languages"],
            "flows": s["flows"],
            "sources": s["sources"],
            "sinks": s["sinks"],
            "gaps": s["gaps"],
            "findings": s["findings"],
            "by_severity": s["by_severity"],
            "processors": s["processors"],
            "wall_seconds": round(wall, 2),
            "peak_rss_mib": rss,
        }
        print(f"{name}: exit {code}, {s['flows']} flows, {s['gaps']} gaps, {wall:.1f} s, {rss} MiB", file=sys.stderr)

    order = [e["name"] for e in corpus["repositories"]]
    summary = {
        "piiflow": {"version": version, "commit": commit, "source_dirty": dirty, "binary_sha256": sha256(args.binary)},
        "machine": {"system": platform.system(), "machine": platform.machine()},
        "applications": [apps[n] for n in order if n in apps],
    }
    summary_path.parent.mkdir(parents=True, exist_ok=True)
    summary_path.write_text(json.dumps(summary, indent=2, sort_keys=True) + "\n")


if __name__ == "__main__":
    main()
