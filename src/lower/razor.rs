//! Razor components (`.razor`): generated C# for the C# lowering, with a map back.
//!
//! There is no maintained tree-sitter grammar for Razor, so a component is translated here into
//! the C# the Razor compiler would make of it, as far as data flow goes, and that C# is lowered
//! like any other file. A byte map takes every generated position back to the `.razor` file, so
//! findings and citations point at the component's own lines.
//!
//! - **Directives:** `@using` (and those of every `_Imports.razor` above the file) become usings;
//!   `@page` a `[Route]` attribute; `@attribute`, `@inherits`, `@implements` and `@typeparam` go
//!   on the class; `@inject T Name` is an injected property.
//! - **`@code` / `@functions`** are copied as class members, unchanged.
//! - **Markup** becomes a render method: `@expr` and `@(expr)` are evaluated (rendering into the
//!   user's own page is not a sink), `@if`/`@foreach`/`@switch`/`@{ }` keep their C# with the
//!   markup inside them translated, and event attributes are handlers.
//! - **`@bind`** sets the bound value from what the user enters: it is assigned the result of
//!   `EventCallbackFactoryBinderExtensions.CreateBinder()`, which is what the Razor compiler
//!   generates and what the catalogue names as a source.
//! - **Component tags** pass their attributes to the child component's properties:
//!   `<OrderRow Order="@o" />` is `new OrderRow { Order = o }`.

/// What a component's generated code depends on outside its own file.
#[derive(Clone, Debug, Default)]
pub struct RazorCtx {
    /// The namespace of the component: `@namespace`, else the project's root namespace and the
    /// folders below the project.
    pub namespace: String,
    /// `@using` lines of the `_Imports.razor` files above the component (outermost first).
    pub imports: Vec<String>,
}

impl RazorCtx {
    /// The context of a component: the project it belongs to (its directory and root
    /// namespace) and the `_Imports.razor` files of the scan (by directory).
    pub fn for_file(
        path: &str,
        project_dir: &str,
        root_namespace: &str,
        imports: &std::collections::BTreeMap<String, String>,
    ) -> RazorCtx {
        let dir = path.rsplit_once('/').map_or("", |(d, _)| d);
        let rel = dir
            .strip_prefix(project_dir)
            .unwrap_or(dir)
            .trim_start_matches('/');
        let mut namespace = root_namespace.to_string();
        for seg in rel.split('/').filter(|s| !s.is_empty()) {
            let seg: String = seg
                .chars()
                .map(|c| {
                    if c.is_alphanumeric() || c == '_' {
                        c
                    } else {
                        '_'
                    }
                })
                .collect();
            if namespace.is_empty() {
                namespace = seg;
            } else {
                namespace = format!("{namespace}.{seg}");
            }
        }
        // `_Imports.razor` from the project's directory down to the component's.
        let mut lines = Vec::new();
        let mut dirs = Vec::new();
        let mut d = dir;
        loop {
            dirs.push(d);
            if d.is_empty() || d == project_dir {
                break;
            }
            d = d.rsplit_once('/').map_or("", |(a, _)| a);
        }
        for d in dirs.into_iter().rev() {
            if let Some(text) = imports.get(d) {
                for line in text.lines() {
                    let t = line.trim().trim_start_matches('\u{feff}');
                    if let Some(u) = t.strip_prefix("@using ") {
                        lines.push(u.trim().trim_end_matches(';').to_string());
                    }
                }
            }
        }
        RazorCtx {
            namespace,
            imports: lines,
        }
    }
}

/// Generated C#, and where each part came from.
#[derive(Clone, Debug, Default)]
pub struct Generated {
    pub text: String,
    /// (generated start, source start, length); a length of 0 marks synthesized text.
    segments: Vec<(usize, usize, usize)>,
}

impl Generated {
    /// The source byte a generated byte came from.
    pub fn to_source(&self, g: usize) -> usize {
        let i = match self.segments.binary_search_by(|s| s.0.cmp(&g)) {
            Ok(i) => i,
            Err(0) => return 0,
            Err(i) => i - 1,
        };
        let (gs, ss, len) = self.segments[i];
        if g < gs + len {
            ss + (g - gs)
        } else {
            ss + len
        }
    }
}

/// The usings the Razor compiler adds to every component.
const DEFAULT_USINGS: &[&str] = &[
    "System",
    "System.Collections.Generic",
    "System.Linq",
    "System.Threading.Tasks",
    "Microsoft.AspNetCore.Components",
];

const CONTROL: &[&str] = &[
    "if", "foreach", "for", "while", "switch", "using", "lock", "try", "do",
];

const VOID_ELEMENTS: &[&str] = &[
    "area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "source", "track",
    "wbr",
];

struct Gen<'s> {
    src: &'s str,
    b: &'s [u8],
    out: Generated,
    members: Generated,
}

impl Gen<'_> {
    fn verbatim(dst: &mut Generated, src: &str, start: usize, end: usize) {
        if end <= start {
            return;
        }
        dst.segments.push((dst.text.len(), start, end - start));
        dst.text.push_str(&src[start..end]);
    }

    fn synth(dst: &mut Generated, at: usize, text: &str) {
        dst.segments.push((dst.text.len(), at, 0));
        dst.text.push_str(text);
    }

    fn code(&mut self, start: usize, end: usize) {
        Self::verbatim(&mut self.out, self.src, start, end);
    }

    fn put(&mut self, at: usize, text: &str) {
        Self::synth(&mut self.out, at, text);
    }

    fn peek(&self, i: usize) -> u8 {
        self.b.get(i).copied().unwrap_or(0)
    }

    fn starts(&self, i: usize, s: &str) -> bool {
        self.src.get(i..).is_some_and(|r| r.starts_with(s))
    }

    /// Past a C# string, char literal or comment starting at `i` (or `i` itself).
    fn skip_literal(&self, i: usize, end: usize) -> usize {
        let b = self.b;
        match b[i] {
            b'"' => {
                // A raw string `"""..."""`.
                if self.starts(i, "\"\"\"") {
                    return self.src[i + 3..end]
                        .find("\"\"\"")
                        .map_or(end, |j| i + 3 + j + 3);
                }
                let verbatim =
                    i > 0 && b[i - 1] == b'@' || i > 1 && (b[i - 1] == b'$' && b[i - 2] == b'@');
                let mut j = i + 1;
                while j < end {
                    match b[j] {
                        b'\\' if !verbatim => j += 2,
                        b'"' if verbatim && j + 1 < end && b[j + 1] == b'"' => j += 2,
                        b'"' => return j + 1,
                        _ => j += 1,
                    }
                }
                end
            }
            b'\'' => {
                let mut j = i + 1;
                while j < end {
                    match b[j] {
                        b'\\' => j += 2,
                        b'\'' => return j + 1,
                        b'\n' => return j,
                        _ => j += 1,
                    }
                }
                end
            }
            b'/' if self.peek(i + 1) == b'/' => self.src[i..end].find('\n').map_or(end, |j| i + j),
            b'/' if self.peek(i + 1) == b'*' => self.src[i + 2..end]
                .find("*/")
                .map_or(end, |j| i + 2 + j + 2),
            _ => i,
        }
    }

    /// The index just past the bracket matching the one at `i` (`(`, `[` or `{`), skipping
    /// literals.
    fn matching(&self, i: usize, end: usize) -> usize {
        let (open, close) = match self.b[i] {
            b'(' => (b'(', b')'),
            b'[' => (b'[', b']'),
            _ => (b'{', b'}'),
        };
        let mut depth = 0;
        let mut j = i;
        while j < end {
            let c = self.b[j];
            let k = self.skip_literal(j, end);
            if k != j {
                j = k;
                continue;
            }
            if c == open {
                depth += 1;
            } else if c == close {
                depth -= 1;
                if depth == 0 {
                    return j + 1;
                }
            }
            j += 1;
        }
        end
    }

    fn ident_end(&self, mut i: usize, end: usize) -> usize {
        while i < end && (self.b[i].is_ascii_alphanumeric() || self.b[i] == b'_') {
            i += 1;
        }
        i
    }

    fn skip_ws(&self, mut i: usize, end: usize) -> usize {
        while i < end && self.b[i].is_ascii_whitespace() {
            i += 1;
        }
        i
    }

    // ---------------------------------------------------------------- markup

    /// Translate markup in `[start, end)`.
    fn markup(&mut self, start: usize, end: usize) {
        let mut i = start;
        while i < end {
            match self.b[i] {
                b'@' => i = self.transition(i, end),
                b'<' if self.peek(i + 1) == b'!' => {
                    // `<!-- -->`, `<!DOCTYPE>`
                    i = self.src[i..end].find('>').map_or(end, |j| i + j + 1);
                }
                b'<' if self.peek(i + 1) == b'/' => {
                    i = self.src[i..end].find('>').map_or(end, |j| i + j + 1);
                }
                b'<' if self.peek(i + 1).is_ascii_alphabetic() => i = self.tag(i, end).0,
                _ => i += 1,
            }
        }
    }

    /// A transition at `@` in markup; returns where markup resumes.
    fn transition(&mut self, at: usize, end: usize) -> usize {
        let i = at + 1;
        // `name@example.com` is text.
        if at > 0 && (self.b[at - 1].is_ascii_alphanumeric() || self.b[at - 1] == b'.') {
            return i;
        }
        match self.peek(i) {
            b'@' => i + 1,
            b'*' => self.src[i..end].find("*@").map_or(end, |j| i + j + 2),
            b'(' => {
                let close = self.matching(i, end);
                self.expression(i, close);
                close
            }
            b'{' => {
                let close = self.matching(i, end);
                self.code_block(i + 1, close.saturating_sub(1).max(i + 1));
                close
            }
            b':' => {
                // `@: text` in a code block: a line of markup.
                let eol = self.src[i..end].find('\n').map_or(end, |j| i + j);
                self.markup(i + 1, eol);
                eol
            }
            c if c.is_ascii_alphabetic() || c == b'_' => {
                let word_end = self.ident_end(i, end);
                let word = &self.src[i..word_end];
                if CONTROL.contains(&word) {
                    return self.control(i, end);
                }
                if matches!(word, "code" | "functions") {
                    let k = self.skip_ws(word_end, end);
                    if self.peek(k) == b'{' {
                        let close = self.matching(k, end);
                        Gen::verbatim(&mut self.members, self.src, k + 1, close - 1);
                        self.members.text.push('\n');
                        return close;
                    }
                }
                if word == "await" {
                    let k = self.skip_ws(word_end, end);
                    let e = self.implicit_end(k, end);
                    self.put(at, "__o = await ");
                    self.code(k, e);
                    self.put(e, ";\n");
                    return e;
                }
                let e = self.implicit_end(i, end);
                self.expression_range(i, e, at);
                e
            }
            _ => i,
        }
    }

    /// The end of an implicit expression: `a.b(c)[d]`, `user?.Name`.
    fn implicit_end(&self, i: usize, end: usize) -> usize {
        let mut j = self.ident_end(i, end);
        loop {
            match self.peek(j) {
                b'(' | b'[' if j < end => j = self.matching(j, end),
                b'.' | b'?'
                    if j + 1 < end
                        && (self.peek(j + 1).is_ascii_alphabetic()
                            || self.peek(j + 1) == b'_'
                            || (self.peek(j) == b'?' && self.peek(j + 1) == b'.')) =>
                {
                    let k = if self.peek(j) == b'?' { j + 2 } else { j + 1 };
                    if !(self.peek(k).is_ascii_alphabetic() || self.peek(k) == b'_') {
                        break;
                    }
                    j = self.ident_end(k, end);
                }
                b'!' if j + 1 < end && self.peek(j + 1) == b'.' => j += 1,
                _ => break,
            }
        }
        j
    }

    /// `(expr)` at `[open, close)`: evaluated.
    fn expression(&mut self, open: usize, close: usize) {
        self.put(open, "__o = ");
        self.code(open, close);
        self.put(close, ";\n");
    }

    fn expression_range(&mut self, start: usize, end: usize, at: usize) {
        if end <= start {
            return;
        }
        self.put(at, "__o = ");
        self.code(start, end);
        self.put(end, ";\n");
    }

    /// `@if (...) { ... } else { ... }`, `@foreach (...) { ... }`, `@try { } catch { }`.
    fn control(&mut self, kw: usize, end: usize) -> usize {
        let first = self.src[kw..self.ident_end(kw, end)].to_string();
        let mut i = kw;
        loop {
            let we = self.ident_end(i, end);
            let word = self.src[i..we].to_string();
            self.code(i, we);
            self.put(we, " ");
            let mut j = self.skip_ws(we, end);
            // `else if`
            if word == "else" && self.starts(j, "if") && self.ident_end(j, end) == j + 2 {
                self.put(j, " ");
                self.code(j, j + 2);
                j = self.skip_ws(j + 2, end);
            }
            if self.peek(j) == b'(' {
                let close = self.matching(j, end);
                self.code(j, close);
                j = self.skip_ws(close, end);
            }
            if self.peek(j) == b'{' {
                let close = self.matching(j, end);
                self.put(j, "{\n");
                self.code_block(j + 1, close.saturating_sub(1).max(j + 1));
                self.put(close.saturating_sub(1), "}\n");
                i = close;
            } else {
                // A single statement without braces: to the end of the line.
                let eol = self.src[j..end].find('\n').map_or(end, |k| j + k);
                self.put(j, "{\n");
                self.code_block(j, eol);
                self.put(eol, "}\n");
                i = eol;
            }
            let k = self.skip_ws(i, end);
            let next = &self.src[k..self.ident_end(k, end)];
            if first == "do" && next == "while" {
                let semi = self.src[k..end].find(';').map_or(end, |x| k + x + 1);
                self.code(k, semi);
                self.put(semi, "\n");
                return semi;
            }
            if matches!(next, "else" | "catch" | "finally") {
                i = k;
                continue;
            }
            return i;
        }
    }

    // ---------------------------------------------------------------- code blocks

    /// C# in `[start, end)` with markup where a statement may start.
    fn code_block(&mut self, start: usize, end: usize) {
        let mut i = start;
        let mut chunk = start;
        let mut at_statement = true;
        while i < end {
            let c = self.b[i];
            let k = self.skip_literal(i, end);
            if k != i {
                i = k;
                at_statement = false;
                continue;
            }
            if c.is_ascii_whitespace() {
                i += 1;
                continue;
            }
            if at_statement && c == b'<' && (self.peek(i + 1).is_ascii_alphabetic()) {
                self.code(chunk, i);
                let e = self.element_end(i, end);
                let inner_text = self.starts(i, "<text>");
                if inner_text {
                    self.markup(i + 6, e.saturating_sub(7).max(i + 6));
                } else {
                    self.markup(i, e);
                }
                i = e;
                chunk = i;
                at_statement = true;
                continue;
            }
            if c == b'@' && self.peek(i + 1) == b':' {
                self.code(chunk, i);
                let eol = self.src[i..end].find('\n').map_or(end, |j| i + j);
                self.markup(i + 2, eol);
                i = eol;
                chunk = i;
                at_statement = true;
                continue;
            }
            if c == b'@' && at_statement {
                // `@if` / `@foreach` inside a code block, or `@expr`.
                self.code(chunk, i);
                i = self.transition(i, end);
                chunk = i;
                continue;
            }
            at_statement = matches!(c, b';' | b'{' | b'}' | b':')
                || (c == b')' && self.closes_header(start, i));
            i += 1;
        }
        self.code(chunk, end);
        self.put(end, "\n");
    }

    /// Whether the `)` at `i` ends a control statement's header (`if (x) <p>...</p>`).
    fn closes_header(&self, start: usize, i: usize) -> bool {
        // Find the matching `(` backwards and the word before it.
        let mut depth = 0;
        let mut j = i;
        while j > start {
            match self.b[j] {
                b')' => depth += 1,
                b'(' => {
                    depth -= 1;
                    if depth == 0 {
                        let mut w = j;
                        while w > start && self.b[w - 1].is_ascii_whitespace() {
                            w -= 1;
                        }
                        let mut s = w;
                        while s > start && self.b[s - 1].is_ascii_alphabetic() {
                            s -= 1;
                        }
                        return matches!(&self.src[s..w], "if" | "foreach" | "for" | "while");
                    }
                }
                _ => {}
            }
            j -= 1;
        }
        false
    }

    /// The end of the element starting at `<` (its matching close tag, or itself when
    /// self-closing or void).
    fn element_end(&self, start: usize, end: usize) -> usize {
        let name_end = self.tag_name_end(start + 1, end);
        let name = &self.src[start + 1..name_end];
        let open_end = self.open_tag_end(name_end, end);
        if self.b[open_end - 1] == b'>' && open_end >= 2 && self.b[open_end - 2] == b'/' {
            return open_end;
        }
        if VOID_ELEMENTS.contains(&name.to_ascii_lowercase().as_str()) {
            return open_end;
        }
        let mut depth = 1;
        let mut i = open_end;
        while i < end {
            if self.b[i] == b'@' && self.peek(i + 1) == b'*' {
                i = self.src[i..end].find("*@").map_or(end, |j| i + j + 2);
                continue;
            }
            if self.b[i] == b'<' {
                if self.peek(i + 1) == b'/' {
                    let ne = self.tag_name_end(i + 2, end);
                    if &self.src[i + 2..ne] == name {
                        depth -= 1;
                        if depth == 0 {
                            return self.src[i..end].find('>').map_or(end, |j| i + j + 1);
                        }
                    }
                } else if self.peek(i + 1).is_ascii_alphabetic() {
                    let ne = self.tag_name_end(i + 1, end);
                    if &self.src[i + 1..ne] == name {
                        let oe = self.open_tag_end(ne, end);
                        if !(self.b[oe - 1] == b'>' && self.b[oe - 2] == b'/') {
                            depth += 1;
                        }
                        i = oe;
                        continue;
                    }
                }
            }
            i += 1;
        }
        end
    }

    fn tag_name_end(&self, mut i: usize, end: usize) -> usize {
        while i < end
            && (self.b[i].is_ascii_alphanumeric() || matches!(self.b[i], b'-' | b'.' | b':' | b'_'))
        {
            i += 1;
        }
        i
    }

    /// The closing quote of an attribute value starting at `i`: quotes inside `@(...)` and
    /// `@x("...")` are C#'s.
    fn quoted_end(&self, mut i: usize, q: u8, end: usize) -> usize {
        while i < end {
            match self.b[i] {
                c if c == q => return i,
                b'@' if self.peek(i + 1) == b'(' => i = self.matching(i + 1, end),
                b'(' => i = self.matching(i, end),
                _ => i += 1,
            }
        }
        end
    }

    /// Past the `>` of an open tag whose name ends at `i`.
    fn open_tag_end(&self, mut i: usize, end: usize) -> usize {
        while i < end {
            match self.b[i] {
                b'"' | b'\'' => {
                    let q = self.b[i];
                    i = (self.quoted_end(i + 1, q, end) + 1).min(end);
                }
                b'@' if self.peek(i + 1) == b'(' => i = self.matching(i + 1, end),
                b'>' => return i + 1,
                _ => i += 1,
            }
        }
        end
    }

    /// An open tag at `<`: its attributes are translated. Returns (end of the open tag, end
    /// of the name).
    fn tag(&mut self, start: usize, end: usize) -> (usize, usize) {
        let name_end = self.tag_name_end(start + 1, end);
        let name = self.src[start + 1..name_end].to_string();
        let component =
            name.chars().next().is_some_and(|c| c.is_ascii_uppercase()) && name != "text";
        let mut params: Vec<(usize, usize, String, bool)> = Vec::new();
        let mut i = name_end;
        let mut tag_end = end;
        while i < end {
            i = self.skip_ws(i, end);
            if i >= end {
                break;
            }
            match self.b[i] {
                b'>' => {
                    tag_end = i + 1;
                    break;
                }
                b'/' if self.peek(i + 1) == b'>' => {
                    tag_end = i + 2;
                    break;
                }
                _ => {}
            }
            // An attribute name.
            let a_start = i;
            while i < end
                && !self.b[i].is_ascii_whitespace()
                && !matches!(self.b[i], b'=' | b'>')
                && !(self.b[i] == b'/' && self.peek(i + 1) == b'>')
            {
                if self.b[i] == b'@' && self.peek(i + 1) == b'(' && i == a_start {
                    i = self.matching(i + 1, end);
                    break;
                }
                i += 1;
            }
            let attr = self.src[a_start..i].to_string();
            let mut value: Option<(usize, usize)> = None;
            let k = self.skip_ws(i, end);
            if self.peek(k) == b'=' {
                let v = self.skip_ws(k + 1, end);
                match self.peek(v) {
                    q @ (b'"' | b'\'') => {
                        let close = self.quoted_end(v + 1, q, end);
                        value = Some((v + 1, close));
                        i = (close + 1).min(end);
                    }
                    _ => {
                        let mut e = v;
                        if self.peek(e) == b'@' && self.peek(e + 1) == b'(' {
                            e = self.matching(e + 1, end);
                        } else {
                            while e < end && !self.b[e].is_ascii_whitespace() && self.b[e] != b'>' {
                                e += 1;
                            }
                        }
                        value = Some((v, e));
                        i = e;
                    }
                }
            }
            self.attribute(a_start, &attr, value, component, &mut params);
        }
        if component {
            // `new Comp { A = x, B = y };`: the child's parameters.
            let has_values = params.iter().any(|(_, _, _, csharp)| *csharp);
            if has_values {
                self.put(start, &format!("__o = new {name} {{ "));
                for (vs, ve, pname, csharp) in &params {
                    if !csharp {
                        continue;
                    }
                    self.put(*vs, &format!("{pname} = "));
                    self.code(*vs, *ve);
                    self.put(*ve, ", ");
                }
                self.put(start, "};\n");
            }
        }
        (tag_end, name_end)
    }

    /// One attribute of a tag.
    fn attribute(
        &mut self,
        at: usize,
        attr: &str,
        value: Option<(usize, usize)>,
        component: bool,
        params: &mut Vec<(usize, usize, String, bool)>,
    ) {
        // `@(expr)` / `@attributes` as an attribute of its own.
        if attr.starts_with("@(") {
            self.expression(at + 1, at + attr.len());
            return;
        }
        let Some((vs, ve)) = value else { return };
        // A value is C# after `@`, or wholly `@(...)`.
        let (cs, ce) = if self.peek(vs) == b'@' && self.peek(vs + 1) == b'(' {
            (
                vs + 2,
                self.matching(vs + 1, ve + 1).saturating_sub(1).min(ve),
            )
        } else if self.peek(vs) == b'@' {
            (vs + 1, ve)
        } else {
            (vs, ve)
        };
        if let Some(rest) = attr.strip_prefix("@bind") {
            if rest.contains(':') {
                // `@bind:after="Handler"` runs a handler; `@bind:format` is text.
                if rest.ends_with(":after") || rest.ends_with(":set") || rest.ends_with(":get") {
                    self.expression_range(cs, ce, at);
                }
                return;
            }
            // `@bind="field"`: the user's input is assigned to it.
            self.code(cs, ce);
            self.put(
                ce,
                " = Microsoft.AspNetCore.Components.EventCallbackFactoryBinderExtensions.CreateBinder();\n",
            );
            return;
        }
        if attr.starts_with("@on") || attr == "@key" || attr == "@attributes" {
            self.expression_range(cs, ce, at);
            return;
        }
        if attr == "@ref" || attr.starts_with("@rendermode") || attr.starts_with("@formname") {
            return;
        }
        let csharp_value = self.peek(vs) == b'@' || (component && self.is_member_chain(vs, ve));
        if component
            && !attr.starts_with('@')
            && attr.chars().next().is_some_and(|c| c.is_ascii_uppercase())
        {
            params.push((cs, ce, attr.to_string(), csharp_value));
            return;
        }
        // A plain attribute: its `@` expressions are evaluated.
        if self.peek(vs) == b'@' {
            self.expression_range(cs, ce, at);
            return;
        }
        let mut i = vs;
        while i < ve {
            if self.b[i] == b'@' {
                i = self.transition(i, ve);
            } else {
                i += 1;
            }
        }
    }

    /// Whether `[s, e)` is a member chain (`Info`, `model.Address`): for a component's
    /// parameter that is not a string, a C# expression.
    fn is_member_chain(&self, s: usize, e: usize) -> bool {
        let t = &self.src[s..e];
        !t.is_empty()
            && t.split('.').all(|p| {
                !p.is_empty()
                    && p.chars()
                        .next()
                        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
                    && p.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
            })
            && !matches!(t, "true" | "false")
    }
}

/// Translate a component into C#.
pub fn generate(path: &str, src: &str, ctx: &RazorCtx) -> Generated {
    let stem = path
        .rsplit('/')
        .next()
        .unwrap_or(path)
        .trim_end_matches(".razor")
        .replace(['.', '-'], "_");
    let mut g = Gen {
        src,
        b: src.as_bytes(),
        out: Generated::default(),
        members: Generated::default(),
    };
    let mut namespace = ctx.namespace.clone();
    let mut usings: Vec<String> = DEFAULT_USINGS.iter().map(|s| s.to_string()).collect();
    usings.extend(ctx.imports.iter().cloned());
    let mut attrs: Vec<(usize, String)> = Vec::new();
    let mut bases: Vec<(usize, String)> = Vec::new();
    let mut base: Option<(usize, String)> = None;
    let mut type_params: Vec<String> = Vec::new();
    // Directives: lines that start with `@word ` at the top level.
    let mut markup_ranges: Vec<(usize, usize)> = Vec::new();
    let mut injects: Vec<(usize, usize, usize, usize)> = Vec::new();
    let end = src.len();
    let mut i = 0;
    let mut markup_start = 0;
    while i < end {
        let line_end = src[i..].find('\n').map_or(end, |j| i + j + 1);
        let t = src[i..line_end].trim_start_matches('\u{feff}');
        let lead = line_end - i - t.len();
        let trimmed = t.trim_start();
        let at = i + lead + (t.len() - trimmed.len());
        let directive = trimmed.strip_prefix('@').map(|r| {
            r.split(|c: char| !(c.is_ascii_alphanumeric()))
                .next()
                .unwrap_or("")
        });
        let arg = |name: &str| {
            trimmed[1 + name.len()..]
                .trim()
                .trim_end_matches(';')
                .to_string()
        };
        match directive {
            Some(
                d @ ("using" | "namespace" | "page" | "inject" | "inherits" | "implements"
                | "attribute" | "typeparam" | "layout" | "rendermode" | "preservewhitespace"),
            ) if !(d == "using" && trimmed[6..].trim_start().starts_with('(')) => {
                if at > markup_start {
                    markup_ranges.push((markup_start, at));
                }
                let a = arg(d);
                match d {
                    "using" => usings.push(a),
                    "namespace" => namespace = a,
                    "page" => attrs.push((
                        at,
                        format!("Microsoft.AspNetCore.Components.RouteAttribute({a})"),
                    )),
                    "attribute" => attrs.push((
                        at,
                        a.trim_start_matches('[').trim_end_matches(']').to_string(),
                    )),
                    "inherits" => base = Some((at, a)),
                    "implements" => bases.push((at, a)),
                    "typeparam" => {
                        type_params.push(a.split_whitespace().next().unwrap_or("").to_string())
                    }
                    "inject" => {
                        // `@inject T Name`: the type and the name, as written.
                        let body = at + 1 + d.len();
                        let rest = src[body..line_end].trim_end();
                        let lead = rest.len() - rest.trim_start().len();
                        let s = body + lead;
                        let e = body + rest.len();
                        if let Some(sp) = src[s..e].rfind(char::is_whitespace) {
                            injects.push((s, s + sp, s + sp + 1, e));
                        }
                    }
                    _ => {}
                }
                markup_start = line_end;
            }
            _ => {}
        }
        i = line_end;
    }
    if markup_start < end {
        markup_ranges.push((markup_start, end));
    }
    // The class.
    if !namespace.is_empty() {
        Gen::synth(&mut g.out, 0, &format!("namespace {namespace};\n"));
    }
    for u in &usings {
        Gen::synth(&mut g.out, 0, &format!("using {u};\n"));
    }
    for (at, a) in &attrs {
        Gen::synth(&mut g.out, *at, &format!("[{a}]\n"));
    }
    let tps = if type_params.is_empty() {
        String::new()
    } else {
        format!("<{}>", type_params.join(", "))
    };
    let base_text = base
        .map(|(_, b)| b)
        .unwrap_or_else(|| "Microsoft.AspNetCore.Components.ComponentBase".into());
    let mut heritage = vec![base_text];
    heritage.extend(bases.into_iter().map(|(_, b)| b));
    Gen::synth(
        &mut g.out,
        0,
        &format!(
            "public partial class {stem}{tps} : {}\n{{\n",
            heritage.join(", ")
        ),
    );
    for (ts, te, ns, ne) in injects {
        Gen::synth(
            &mut g.out,
            ts,
            "[Microsoft.AspNetCore.Components.InjectAttribute] public ",
        );
        g.code(ts, te);
        g.put(te, " ");
        g.code(ns, ne);
        g.put(ne, " { get; set; }\n");
    }
    g.put(
        0,
        "private void __BuildRenderTree()\n{\nobject __o = null;\n",
    );
    for (s, e) in markup_ranges {
        g.markup(s, e);
    }
    g.put(end, "}\n");
    // `@code` blocks, collected while the markup was translated.
    let members = std::mem::take(&mut g.members);
    let offset = g.out.text.len();
    for (gs, ss, len) in members.segments {
        g.out.segments.push((gs + offset, ss, len));
    }
    g.out.text.push_str(&members.text);
    g.put(end, "}\n");
    g.out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generates_a_component() {
        let src = r#"@page "/checkout"
@using Shop.Models
@inject ILogger<Checkout> Logger
@attribute [Authorize]

<EditForm Model="Info" OnSubmit="@Submit">
    <InputText @bind-Value="Info.Street" />
    @if (Info.Street is not null)
    {
        <p class="x @cls">@Info.Street</p>
        foreach (var l in lines) { <li>@l</li> }
    }
    <button @onclick="() => Clear()">x</button>
    <a href="mailto:me@example.com">@(Total * 2)</a>
</EditForm>

@code {
    [SupplyParameterFromForm]
    public Address Info { get; set; } = default!;
    void Submit() => Logger.LogInformation("{S}", Info.Street);
}
"#;
        let g = generate(
            "Components/Pages/Checkout.razor",
            src,
            &RazorCtx {
                namespace: "Shop.Components.Pages".into(),
                imports: vec!["Shop.Services".into()],
            },
        );
        let t = &g.text;
        assert!(t.contains("namespace Shop.Components.Pages;"), "{t}");
        assert!(t.contains("using Shop.Services;"));
        assert!(t.contains("[Microsoft.AspNetCore.Components.RouteAttribute(\"/checkout\")]"));
        assert!(t.contains("[Authorize]"));
        assert!(t.contains("public ILogger<Checkout> Logger { get; set; }"));
        assert!(t.contains(
            "public partial class Checkout : Microsoft.AspNetCore.Components.ComponentBase"
        ));
        assert!(t.contains("Info.Street = Microsoft.AspNetCore.Components.EventCallbackFactoryBinderExtensions.CreateBinder();"));
        assert!(
            t.contains("__o = new EditForm { Model = Info, OnSubmit = Submit, };"),
            "{t}"
        );
        assert!(t.contains("if (Info.Street is not null)"));
        assert!(t.contains("__o = Info.Street;"));
        assert!(t.contains("__o = cls;"));
        assert!(t.contains("__o = l;"));
        assert!(t.contains("__o = () => Clear();"));
        assert!(t.contains("__o = (Total * 2);"));
        assert!(!t.contains("example"));
        assert!(t.contains("void Submit() => Logger.LogInformation"));
        // The generated code parses.
        let tree = crate::lower::csharp::scan::parser().parse(t, None).unwrap();
        assert!(!tree.root_node().has_error(), "{t}");
        // Positions map back: `Info.Street` in the binder is the source's.
        let g_at = t.find("Info.Street = Microsoft").unwrap();
        let s_at = g.to_source(g_at);
        assert_eq!(&src[s_at..s_at + 11], "Info.Street");
    }
}
